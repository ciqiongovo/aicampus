'use strict'
const assert = require('node:assert/strict')
const fs = require('node:fs')
const vm = require('node:vm')
const ts = require('typescript')
const source = fs.readFileSync(require('node:path').join(__dirname, '../src/renderer/src/modules/mail.tsx'), 'utf8')
const helper = source.slice(source.indexOf('function buildSrcDoc('), source.indexOf('function MailPage('))
assert.ok(helper.startsWith('function buildSrcDoc('))
const context = vm.createContext({})
vm.runInContext(ts.transpileModule(helper, { compilerOptions: { target: ts.ScriptTarget.ES2022 } }).outputText, context)
const html = context.buildSrcDoc('', '<script>alert(1)</script> & plain\ntext')
assert.ok(html.includes('&lt;script&gt;alert(1)&lt;/script&gt; &amp; plain'))
assert.ok(!html.includes('<script>'))
assert.ok(html.includes('<pre>'))
const remote = '<img src="https://example.invalid/image.png">'
assert.ok(context.buildSrcDoc(remote, 'fallback').includes(remote))
assert.ok(!context.buildSrcDoc(remote, 'fallback').includes('<pre>fallback</pre>'))
assert.ok(context.buildSrcDoc('', '').includes('</body></html>'))
console.log('mail-view: plaintext escaped, HTML/image preserved, empty body valid: PASS')
