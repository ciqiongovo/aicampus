test('preference-only updates persist a small revisioned file without rewriting historical tags', async t => {
  const dir = mkdtempSync(join(tmpdir(), 'infoagent-pref-small-'))
  t.after(() => rmSync(dir, { recursive: true, force: true }))
  const path = join(dir, 'mail-tags.json')
  const weights = Object.fromEntries(MAIL_PARENT_LABELS.map(x => [x.id, 5]))
  const tags = Object.fromEntries(Array.from({ length: 2000 }, (_, id) => [id, { classifier: 4, marker: 'x'.repeat(1000) }]))
  const original = JSON.stringify({ version: 2, preferences: { parentWeights: weights, updatedAt: null }, tags })
  writeFileSync(path, original)
  const service = new MailTagService(path)
  await Promise.all(Array.from({ length: 5 }, () => service.adjustPreference({ competition: 0.35 })))
  assert.ok(Math.abs((await service.preferencesGet()).parentWeights.competition - 6.75) < 1e-9)
  assert.equal(readFileSync(path, 'utf8'), original)
  const sidecar = readFileSync(path + '.preferences.json', 'utf8')
  assert.ok(sidecar.length < 1000)
  assert.ok(!sidecar.includes('marker'))
  assert.equal(JSON.parse(sidecar).revision, 5)
  const restarted = new MailTagService(path)
  assert.deepEqual(await restarted.preferencesGet(), await service.preferencesGet())
  // A subsequent generic tag transaction embeds the current revision; stale sidecars cannot win on restart.
  await restarted.transact(data => { data.preferences.parentWeights.competition = 8; data.preferences.updatedAt = 'test-later' })
  const afterTags = new MailTagService(path)
  assert.equal((await afterTags.preferencesGet()).parentWeights.competition, 8)
  await afterTags.adjustPreference({ competition: -0.35 })
  assert.equal((await new MailTagService(path).preferencesGet()).parentWeights.competition, 7.65)
})

test('failed small preference writes leave memory and historical file intact and the queue can retry', async t => {
  const dir = mkdtempSync(join(tmpdir(), 'infoagent-pref-failure-'))
  t.after(() => rmSync(dir, { recursive: true, force: true }))
  const path = join(dir, 'mail-tags.json')
  const service = new MailTagService(path)
  const before = await service.preferencesGet()
  mkdirSync(path + '.preferences.json')
  await assert.rejects(service.adjustPreference({ competition: 1 }))
  assert.deepEqual(await service.preferencesGet(), before)
  rmSync(path + '.preferences.json', { recursive: true })
  await service.adjustPreference({ competition: 1 })
  assert.equal((await new MailTagService(path).preferencesGet()).parentWeights.competition, 6)
})

test('邮件评级反馈按雷达灵敏度缩放八维权重', async () => {
  const dir = mkdtempSync(join(tmpdir(), 'infoagent-radar-sensitivity-'))
  const db = openDatabase(join(dir, 'mail.db'))
  try {
    const accountId = insertAccount(db, {provider:'qq',label:'测试',address:'b@qq.com',host:'imap.qq.com',port:993,encryption:'ssl',username:'b@qq.com',secret_enc:'encrypted',folder:'INBOX',auth_mode:'appPassword',last_uidvalidity:null,last_uid:null,last_sync_at:null,sync_error:null})
    const id = upsertEmail(db, {account_id:accountId,folder:'INBOX',uid:21,message_id:'<m21@example.com>',subject:'黑客松竞赛',from_addr:'teacher@example.com',to_addr:'b@qq.com',cc:'',date_utc:new Date().toISOString(),date_raw:null,unread:1,body_text:'正文',body_html:'',attachments_json:'[]',size:15})
    const service = new MailTagService(join(dir, 'mail-tags.json'))
    setSetting(db, 'radarSensitivity', 'veryLow')
    await service.feedback(db, id, { rating: 'A' })
    assert.equal((await service.preferencesGet()).parentWeights.competition, 5.25)
    setSetting(db, 'radarSensitivity', 'veryHigh')
    await service.feedback(db, id, { rating: 'A' })
    assert.equal((await service.preferencesGet()).parentWeights.competition, 7.25)
    setSetting(db, 'radarSensitivity', 'invalid')
    await service.feedback(db, id, { rating: 'A' })
    assert.equal((await service.preferencesGet()).parentWeights.competition, 8.25)
  } finally { db.close(); rmSync(dir,{recursive:true,force:true}) }
})

test('邮件标签落专文件、动态评级及偏好，反馈覆写不被分析覆盖', async () => {
  const dir = mkdtempSync(join(tmpdir(), 'infoagent-mail-tags-'))
  const path = join(dir, 'mail-tags.json')
  const db = openDatabase(join(dir, 'mail.db'))
  try {
    const accountId = insertAccount(db, {provider:'qq',label:'测试',address:'a@qq.com',host:'imap.qq.com',port:993,encryption:'ssl',username:'a@qq.com',secret_enc:'encrypted',folder:'INBOX',auth_mode:'appPassword',last_uidvalidity:null,last_uid:null,last_sync_at:null,sync_error:null})
    const base = {account_id:accountId,folder:'INBOX',uid:11,message_id:'<m11@example.com>',subject:'黑客松竞赛校园活动',from_addr:'teacher@example.com',to_addr:'a@qq.com',cc:'',date_utc:new Date().toISOString(),date_raw:null,unread:1,body_text:'机密正文',body_html:'',attachments_json:'[]',size:15}
    const id = upsertEmail(db, base)
    const id2 = upsertEmail(db, {...base,uid:12,message_id:'<m12@example.com>',subject:'黑客松竞赛'})
    const service = new MailTagService(path)
    const weights = Object.fromEntries(MAIL_PARENT_LABELS.map(x => [x.id, 2]))
    weights.competition = 8
    await service.preferencesSet(weights)
    const listed = await service.list(db)
    assert.equal(listed.total, 2)
    assert.equal(listed.items.length, 2)
    const record = await service.get(db, id)
    assert.deepEqual(record.parentLabels.sort(), ['activities','competition'])
    assert.equal(record.interest, 8)
    assert.equal(record.tier, 1)
    assert.ok(record.subLabels.length >= 2 && record.subLabels.length <= 5)
    assert.ok(record.subLabels.every(label => label.length <= 12), '子标签应是分类词，不能截断标题')
    const persisted = JSON.parse(readFileSync(path, 'utf8'))
    assert.equal(persisted.tags[id].accountId, accountId)
    assert.equal(persisted.tags[id].uid, 11)
    assert.equal(persisted.tags[id].messageId, '<m11@example.com>')
    assert.equal(persisted.tags[id2].uid, 12)
    assert.ok(!readFileSync(path, 'utf8').includes('机密正文'))
    const manual = await service.feedback(db, id, {parentLabels:['student','career'],subLabels:['自定义词','另一短词'],interest:2,urgency:'within_1d'})
    assert.equal(manual.tier, 4)
    assert.equal(manual.urgency, 'within_1d')
    await service.preferencesSet({...weights, competition:5})
    assert.equal((await service.get(db,id2)).interest,5)
    assert.equal((await service.get(db,id)).interest,2)
    await service.refreshFromAnalysis(db,id)
    assert.deepEqual((await service.get(db,id)).parentLabels,['student','career'])
    const deadline = new Date(Date.now()+25*60*60*1000).toISOString()
    upsertAnalysis(db,{email_id:id2,status:'analyzed',category:'可选机会',summary:'黑客松竞赛',action_required:null,deadline_raw:'明天',deadline_at:deadline,deadline_kind:'deadline',event_start_at:null,applicable_to:null,confidence:0.9,tier:'review',evidence_json:'[]',model:'demo',provider:'demo',error:null,analyzed_at:new Date().toISOString()})
    await service.refreshFromAnalysis(db,id2)
    assert.equal((await service.get(db,id2)).urgency,'within_3d')
    const rated = await service.feedback(db,id2,{rating:'A'})
    assert.ok(rated.interest > 5)
    assert.equal((await service.preferencesGet()).parentWeights.competition,6)
    const restarted = new MailTagService(path)
    assert.equal((await restarted.get(db,id)).interest,2)
    assert.ok((await restarted.get(db,id2)).interest > 5)
    await assert.rejects(restarted.feedback(db,id,{subLabels:['单个']}), /2–5/)
    await assert.rejects(restarted.feedback(db,id,{parentLabels:['unknown']}), /不合法/)
    assert.equal((await restarted.feedback(db,id,{tier:2})).interest,5)
    await assert.rejects(restarted.feedback(db,id,{tier:4,interest:9}), /冲突/)
    await assert.rejects(restarted.preferencesSet({...weights, career:11}), /0–10/)
    assert.equal(await restarted.get(db,999999),null)
    await restarted.refreshFromAnalysis(db,id2)
    assert.equal((await restarted.get(db,id2)).urgency,'within_3d')
    assert.equal(JSON.parse(readFileSync(path,'utf8')).tags[id2].deadlineAt,deadline)
    const id3 = upsertEmail(db,{...base,uid:13,message_id:'<m13@example.com>',subject:'课程安排'})
    assert.equal((await restarted.get(db,id3)).source,'fallback')
    upsertAnalysis(db,{email_id:id3,status:'analyzed',category:'重要通知',summary:'课程安排',action_required:null,deadline_raw:'明天',deadline_at:deadline,deadline_kind:'deadline',event_start_at:null,applicable_to:null,confidence:0.9,tier:'review',evidence_json:'[]',model:'demo',provider:'demo',error:null,analyzed_at:new Date().toISOString()})
    assert.equal((await restarted.get(db,id3)).source,'analysis')
    assert.equal((await restarted.get(db,id3)).urgency,'within_3d')
  } finally { db.close(); rmSync(dir,{recursive:true,force:true}) }
})
