'use strict'
const { test } = require('node:test')
const assert = require('node:assert/strict')
const { mkdtempSync, readFileSync, writeFileSync, mkdirSync, rmSync } = require('node:fs')
const { tmpdir } = require('node:os')
const { join } = require('node:path')
const { openDatabase } = require('../.test-out/main/db/database.js')
const { MailTagService } = require('../.test-out/main/services/mailTags.js')
const { MAIL_PARENT_LABELS } = require('../.test-out/shared/mailTags.js')
const { insertAccount } = require('../.test-out/main/db/dao/accountsDao.js')
const { upsertEmail } = require('../.test-out/main/db/dao/emailsDao.js')
